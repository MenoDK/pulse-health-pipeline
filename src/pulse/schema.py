"""Table definitions for query building (SQLAlchemy Core).

The migrations in `alembic/versions` are the source of truth for the database. `tests/test_schema.py` reflects the
migrated database and compares it with these definitions, so the two cannot drift apart without a red test.

Data minimisation is a property of this schema, not a promise: there is no column for a name, a national identifier,
a phone number or an e-mail address, and a test walks the whole database looking for the identifiers it generated.
"""

from __future__ import annotations

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    Boolean,
    Column,
    Computed,
    Date,
    DateTime,
    Integer,
    MetaData,
    Table,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR

EMBEDDING_DIM = 256

metadata = MetaData()

teams = Table(
    "teams",
    metadata,
    Column("team_id", Text, primary_key=True),
    Column("name", Text, nullable=False),
    Column("kind", Text, nullable=False),
    Column("active", Boolean, nullable=False),
    Column("version", Integer, nullable=False),
    Column("source_updated_at", DateTime(timezone=True), nullable=False),
)

subjects = Table(
    "subjects",
    metadata,
    Column("subject_key", Text, primary_key=True),  # a keyed hash of the registry id, never the id itself
    Column("key_id", Text, nullable=False),
    Column("team_id", Text),
    Column("birth_month", Date, nullable=False),  # truncated to the month: enough for an age band, less identifying
    Column("chronic", Boolean, nullable=False),
    Column("registered_on", Date, nullable=False),
    Column("registry_refreshed_on", Date, nullable=False),
    Column("version", Integer, nullable=False),
    Column("deleted", Boolean, nullable=False),
    Column("source_updated_at", DateTime(timezone=True), nullable=False),
)

encounters = Table(
    "encounters",
    metadata,
    Column("encounter_id", Text, primary_key=True),
    Column("subject_key", Text, nullable=False),
    Column("team_id", Text),
    Column("kind", Text, nullable=False),
    Column("occurred_on", Date, nullable=False),
    Column("version", Integer, nullable=False),
    Column("deleted", Boolean, nullable=False),
    Column("source_updated_at", DateTime(timezone=True), nullable=False),
)

sync_state = Table(
    "sync_state",
    metadata,
    Column("entity", Text, primary_key=True),
    Column(
        "cursor_updated_at", DateTime(timezone=True)
    ),  # a time only: no registry record id is stored, here or anywhere
    Column("updated_at", DateTime(timezone=True), nullable=False),
)

sync_runs = Table(
    "sync_runs",
    metadata,
    Column("id", BigInteger, primary_key=True, autoincrement=True),
    Column("started_at", DateTime(timezone=True), nullable=False),
    Column("finished_at", DateTime(timezone=True)),
    Column("status", Text, nullable=False),
    Column("pages", Integer, nullable=False),
    Column("fetched", Integer, nullable=False),
    Column("applied", Integer, nullable=False),
    Column("stale", Integer, nullable=False),
    Column("rejected", Integer, nullable=False),
    Column("error", Text),
)

outbox = Table(
    "outbox",
    metadata,
    Column("id", BigInteger, primary_key=True, autoincrement=True),
    Column("idempotency_key", Text, nullable=False, unique=True),
    Column("kind", Text, nullable=False),
    Column("payload", JSONB, nullable=False),
    Column("status", Text, nullable=False),
    Column("attempts", Integer, nullable=False),
    Column("not_before", DateTime(timezone=True), nullable=False),
    Column("lease_until", DateTime(timezone=True)),
    Column("locked_by", Text),
    Column("last_status", Integer),
    Column("last_error", Text),
    Column("created_at", DateTime(timezone=True), nullable=False),
    Column("updated_at", DateTime(timezone=True), nullable=False),
    Column("done_at", DateTime(timezone=True)),
)

outbox_attempts = Table(
    "outbox_attempts",
    metadata,
    Column("id", BigInteger, primary_key=True, autoincrement=True),
    Column("outbox_id", BigInteger, nullable=False),
    Column("at", DateTime(timezone=True), nullable=False),
    Column("outcome", Text, nullable=False),
    Column("http_status", Integer),
    Column("detail", Text),
)

kb_chunks = Table(
    "kb_chunks",
    metadata,
    Column("id", BigInteger, primary_key=True, autoincrement=True),
    Column("doc_id", Text, nullable=False),
    Column("chunk_no", Integer, nullable=False),
    Column("title", Text, nullable=False),
    Column("category", Text, nullable=False),
    Column("content", Text, nullable=False),
    Column("embedding", Vector(EMBEDDING_DIM), nullable=False),
    # Generated by the database from title and content, so an insert can never leave it stale.
    Column("tsv", TSVECTOR, Computed("to_tsvector('english', title || ' ' || content)", persisted=True)),
)

health_samples = Table(
    "health_samples",
    metadata,
    Column("id", BigInteger, primary_key=True, autoincrement=True),
    Column("at", DateTime(timezone=True), nullable=False),
    Column("component", Text, nullable=False),
    Column("status", Text, nullable=False),
    Column("latency_ms", Integer),
    Column("detail", Text),
)

heartbeats = Table(
    "heartbeats",
    metadata,
    Column("component", Text, primary_key=True),
    Column("at", DateTime(timezone=True), nullable=False),
)

lab_state = Table(
    "lab_state",
    metadata,
    Column("key", Text, primary_key=True),
    Column("value", JSONB, nullable=False),
)
